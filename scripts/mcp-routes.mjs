// Builds src/admin/mcproutes.ts: the dashboard API's routes (method, path, the comment above them), for the Claude
// connector's api_routes tool. Run: node scripts/mcp-routes.mjs   (a test checks it is up to date)
import fs from "node:fs";
const FILES = ["src/admin/api.ts", "src/admin/learnapi.ts", "src/admin/misesapi.ts", "src/admin/actapi.ts", "src/admin/vscapi.ts"];
export function routes() {
  const out = [];
  for (const f of FILES) {
    const lines = fs.readFileSync(f, "utf8").replace(/\r/g, "").split("\n");
    lines.forEach((l, i) => {
      const exact = [...l.matchAll(/path === "(\/[^"]*)"(?:\s*&&\s*method === "(\w+)")?/g)];
      const rx = [...l.matchAll(/path\.match\(\/\^(.+?)\$\/\)\)?(?:\)?\s*&&\s*method (?:===|!==) "(\w+)")?/g)];
      if (!exact.length && !rx.length) return;
      // the comment just above (one or two lines), the route's own words
      let note = "";
      for (let j = i - 1; j >= Math.max(0, i - 3); j--) { const c = lines[j].trim(); if (c.startsWith("//")) note = c.replace(/^\/\/\s*/, "") + (note ? " " + note : ""); else break; }
      for (const m of exact) out.push({ method: m[2] || "ANY", path: m[1], note });
      for (const m of rx) out.push({ method: m[2] || "ANY", path: m[1].replace(/\\\//g, "/").replace(/\(\\d\+\)|\(\\d\{[\d,]+\}\)/g, ":id").replace(/\(\[\^\/\]\+\)|\(\[\\w-\]\{[\d,]+\}\)/g, ":x"), note });
    });
  }
  const seen = new Set();
  return out.filter((r) => { const k = r.method + " " + r.path; if (seen.has(k)) return false; seen.add(k); return true; }).map((r) => ({ ...r, note: r.note.replace(/-{4,}\s*/g, "").trim().slice(0, 220) }));
}
const body = `// Generated by scripts/mcp-routes.mjs: the dashboard API's routes for the Claude connector (api_routes). Don't edit.\nexport const ROUTES: { method: string; path: string; note: string }[] = ${JSON.stringify(routes(), null, 0).replace(/},{/g, "},\n  {")};\n`;
if (process.argv[1]?.endsWith("mcp-routes.mjs")) { fs.writeFileSync("src/admin/mcproutes.ts", body); console.log(`${routes().length} routes`); }
export { body };
