"""Builds src/shared/font.ts: a small 2-bit anti-aliased monospace glyph atlas
(DejaVu Sans Mono, free license) used to draw code as PNG images in the Worker."""
import base64
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
SIZE, W, H = 17, 10, 21
CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(0xC0, 0x100)] + ["→", "←", "…", "≤", "≥", "≠", "×", "²", "³", "°", "€", "’", "“", "”", "–", "—", "•"]
font = ImageFont.truetype(FONT, SIZE)
ascent, descent = font.getmetrics()
bits = []
for ch in CHARS:
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    d.text((0, (H - (ascent + descent)) // 2), ch, font=font, fill=255)
    for y in range(H):
        for x in range(W):
            v = img.getpixel((x, y))
            bits.append(min(3, (v + 42) // 85))
packed = bytearray()
for i in range(0, len(bits), 4):
    b = 0
    for k, v in enumerate(bits[i:i + 4]):
        b |= v << (6 - 2 * k)
    packed.append(b)
out = f"""// Generated by tools/gen_font.py from DejaVu Sans Mono (Bitstream Vera / DejaVu free license).
// {len(CHARS)} glyphs of {W}x{H} pixels, 2 bits per pixel (0 = background … 3 = ink).
export const GLYPH_W = {W};
export const GLYPH_H = {H};
export const GLYPH_CHARS = {''.join(CHARS)!r};
export const GLYPHS_B64 = "{base64.b64encode(bytes(packed)).decode()}";
"""
(ROOT / "src/shared/font.ts").write_text(out.replace("'", '"', 0), encoding="utf-8")
print(len(CHARS), "glyphs,", len(packed), "bytes")
